// bin/reference/render-env.test.mjs
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

import { headings, parseFrontmatter } from "../lib/frontmatter.mjs";
import { parseEnvReference } from "./env-parser.mjs";
import { repoRoot } from "./manifest.mjs";
import { inlineCode, renderEnvironmentPage, RENDERER_STRINGS } from "./render-env.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const fixture = (name) => readFileSync(join(here, "fixtures", name), "utf8");

const manifest = {
  extractorFormatVersion: 1,
  upstream: {
    repository: "https://github.com/onetimesecret/onetimesecret",
    release: "v9.9.9",
    commit: "0123456789abcdef0123456789abcdef01234567",
  },
  refreshOwner: "someone",
  backupReviewer: "someone-else",
  files: [{ path: ".env.reference", role: "env-reference", sha256: "x".repeat(64), lines: 80 }],
};

const rendered = renderEnvironmentPage({
  parsed: parseEnvReference(fixture("sample.envref"), { sourceName: ".env.reference" }),
  manifest,
});
const page = rendered.page;
const { fields, body } = parseFrontmatter(page);

describe("inlineCode", () => {
  it("escapes a pipe so a value cannot split a table row", () => {
    expect(inlineCode("keep|me")).toBe("`keep\\|me`");
  });

  it("picks a backtick run longer than any in the value", () => {
    expect(inlineCode("`rm -rf /`")).toBe("`` `rm -rf /` ``");
    expect(inlineCode("a ``b`` c")).toBe("```a ``b`` c```");
  });

  it("leaves an ordinary value alone", () => {
    expect(inlineCode("production")).toBe("`production`");
  });
});

describe("frontmatter", () => {
  it("fills the fields the page contract requires", () => {
    expect(fields.title).toBe("Environment variables");
    expect(fields.description).not.toBe("");
    expect(fields.audience).toBe("operator");
    expect(fields.pageType).toBe("reference");
    expect(fields.sourceOfTruth).toMatch(/^onetimesecret\/\.env\.reference:1-80 \(/);
  });

  it("does not enroll the page in TextProv: it is generated, not authored", () => {
    expect(fields.textprov).toBeUndefined();
  });

  it("states the source release once, in a single sentence", () => {
    expect(body).toContain("This reference reflects Onetime Secret v9.9.9 (`01234567`).");
    expect(body.match(/v9\.9\.9/g)).toHaveLength(1);
  });

  it("starts the body at a level-two heading", () => {
    expect(headings(body).some((heading) => heading.depth === 1)).toBe(false);
    expect(headings(body)[0]).toMatchObject({ depth: 2 });
  });
});

describe("structure", () => {
  it("renders one level-two heading per published section and one level-three per variable", () => {
    const h2 = headings(body).filter((heading) => heading.depth === 2);
    const h3 = headings(body).filter((heading) => heading.depth === 3);
    expect(h2.map((heading) => heading.text)).toEqual(["Sample Section"]);
    expect(h3.map((heading) => heading.text)).toContain("ACTIVE_VALUE");
    expect(h3).toHaveLength(16);
  });

  it("drops the development-only section and everything in it", () => {
    expect(body).not.toContain("DEV_ONLY_FLAG");
    expect(headings(body).map((heading) => heading.text)).not.toContain("Development Only");
  });

  it("drops a duplicate and a malformed declaration", () => {
    expect(body).not.toContain("MALFORMED_QUOTE");
    expect(body.match(/^### ACTIVE_VALUE$/gm)).toHaveLength(1);
  });

  it("gives every variable a unique fragment that is the lower-cased name", () => {
    const h3 = headings(body).filter((heading) => heading.depth === 3);
    expect(h3.map((heading) => heading.slug)).toEqual(h3.map((heading) => heading.text.toLowerCase()));
    expect(new Set(h3.map((heading) => heading.slug)).size).toBe(h3.length);
  });
});

describe("source text is verbatim", () => {
  it("renders prose inside a fence so Markdown cannot reinterpret it", () => {
    expect(page).toContain("[derived] reads as a link reference, a pipe | mid-sentence, <b>html</b>,");
  });

  it("uses a fence long enough to hold prose that contains a fence", () => {
    expect(page).toContain("````\nProse that would be Markdown");
  });

  it("copies the source file's header legend without rewording it", () => {
    expect(page).toContain("  * [derived] are generated by `rake ots:init` via HKDF from SECRET.");
  });

  it("drops only the header line that names the file", () => {
    expect(page).not.toContain("# .env.reference");
  });
});

describe("table cells", () => {
  /** The one data row of the table under `### NAME`. */
  const row = (name) => {
    const entry = body.slice(body.indexOf(`### ${name}\n`));
    const line = entry
      .split("\n")
      .find(
        (candidate) =>
          candidate.startsWith("| ") &&
          !candidate.startsWith("| ---") &&
          !candidate.includes(RENDERER_STRINGS.columnSource),
      );
    expect(line, `no data row found for ${name}`).toBeTruthy();
    return line;
  };

  it("shows the source line verbatim, with its comment marker intact", () => {
    expect(row("ACTIVE_VALUE")).toContain("`ACTIVE_VALUE=production`");
    expect(row("COMMENTED_TTL")).toContain("`#COMMENTED_TTL=3600`");
    expect(row("ACTIVE_EMPTY")).toContain("`ACTIVE_EMPTY=`");
  });

  it("keeps a quoted hash and an embedded equals sign in the example", () => {
    expect(row("QUOTED_HASH")).toContain("`#QUOTED_HASH='#3B82F6'`");
    expect(row("URL_WITH_EQUALS")).toContain("'redis://host:6379/0?timeout=5&other=1'");
  });

  it("escapes a pipe in a value instead of splitting the row", () => {
    const cells = row("MARKDOWN_HOSTILE").split(/(?<!\\)\|/);
    expect(cells.filter((cell) => cell.trim() !== "")).toHaveLength(5);
    expect(row("MARKDOWN_HOSTILE")).toContain("keep\\|me");
  });

  it("says a default is not declared rather than reusing the example", () => {
    expect(row("ACTIVE_VALUE")).toContain(RENDERER_STRINGS.cellNoDeclaredDefault);
    expect(row("COMMENTED_TTL")).toContain("`3600`");
  });

  it("reports an unannotated variable as unannotated", () => {
    expect(row("QUOTED_HASH")).toContain(RENDERER_STRINGS.cellNoSince);
    expect(row("ACTIVE_VALUE")).toContain("v0.26.0");
    expect(row("TAGGED_KEY")).toContain("unreleased");
  });

  it("cites the source line span", () => {
    expect(row("ACTIVE_VALUE")).toMatch(/`\.env\.reference:\d+(-\d+)?`/);
  });
});

describe("renderer-introduced prose", () => {
  it("is limited to RENDERER_STRINGS", () => {
    // Everything on the page is either copied source text or one of these.
    // Stripping the fenced source blocks, the frontmatter and the table
    // scaffolding should leave nothing but these strings and the one-sentence
    // preamble.
    expect(Object.keys(RENDERER_STRINGS).sort()).toEqual([
      "cellNoDeclaredDefault",
      "cellNoSince",
      "cellNoTags",
      "columnDeclaredDefault",
      "columnExample",
      "columnSince",
      "columnSource",
      "columnTags",
      "frontmatterDescription",
      "frontmatterSourceOfTruthShape",
      "frontmatterTitle",
      "preamble",
    ]);
  });

  it("introduces no prose paragraph beyond the preamble", () => {
    const withoutFences = body.replace(/^(`{3,})[\s\S]*?^\1$/gm, "");
    const paragraphs = withoutFences
      .split("\n")
      .filter((line) => line.trim() !== "")
      .filter((line) => !line.startsWith("#") && !line.startsWith("|"));
    expect(paragraphs).toEqual(["This reference reflects Onetime Secret v9.9.9 (`01234567`)."]);
  });
});

describe("the tracked page", () => {
  const tracked = readFileSync(join(repoRoot, "src/content/docs/en/reference/environment-variables.md"), "utf8");
  const trackedBody = parseFrontmatter(tracked).body;
  const legacy = parseFrontmatter(
    readFileSync(join(repoRoot, "src/content/docs/en/self-hosting/environment-variables.md"), "utf8"),
  ).body;

  it("keeps every section fragment the legacy page published, except development-only", () => {
    const now = new Set(headings(trackedBody).map((heading) => heading.slug));
    const before = headings(legacy)
      .filter((heading) => heading.depth === 3)
      .map((heading) => heading.slug);
    const missing = before.filter((slug) => !now.has(slug));
    // The one intentional loss: plan section 2 excludes unsupported variables
    // from the supported reference, so there is no Development Only section to
    // land on. Recorded here so adding a second loss fails.
    expect(missing).toEqual(["development-only"]);
  });

  it("has no slugger-suffixed duplicate heading", () => {
    expect(headings(trackedBody).filter((heading) => /-\d+$/.test(heading.slug))).toEqual([]);
  });
});
